"""Phase 6, step 1: prepare forex data for Kronos fine-tuning.

    python -m forexapp.models.finetune.prepare_data --pairs EURUSD,GBPUSD,USDJPY,AUDUSD,XAUUSD \
        --train-end 2024-12-31 --val-end 2025-06-30 --out models/finetune/data

Writes, per pair, a CSV with the columns Kronos' ``finetune_csv`` expects:
timestamps, open, high, low, close, volume (tick count), amount (0). Splits
by TIME, never randomly:

* train: up to --train-end; validation: up to --val-end (both in the trainval CSV,
  with train_ratio / val_ratio set so the split lands on --train-end);
* test: after --val-end, in a separate CSV, untouched until the final comparison.

It also writes a config YAML for ``finetune_csv/train_sequential.py`` that
starts from NeoQuasar/Kronos-Tokenizer-base and Kronos-small and saves under
models/checkpoints/ with the date and data range in the name.

One model for all pairs usually beats one model per pair (more data), so try
both. ``finetune_csv`` sorts every row by timestamp, so two pairs cannot share
one CSV (their candles would interleave). To train one model on all pairs, run
the pairs one after another and point each run's ``pretrained_tokenizer`` and
``pretrained_predictor`` at the previous run's best checkpoints
(``--chain`` writes the configs that way), or use Kronos' ``finetune/``
pipeline, which keeps symbols apart.
"""
from __future__ import annotations

import argparse
import csv
from datetime import datetime, timezone
from pathlib import Path

from ...config import APP_DIR, Config, norm_tf
from ...data.store import Store
from ...timeutil import parse_iso

CONFIG_TEMPLATE = """# Kronos fine-tuning on forex candles (generated by forexapp.models.finetune.prepare_data)
# Run from the Kronos repo:  python finetune_csv/train_sequential.py --config {config_path}
data:
  data_path: "{data_path}"
  lookback_window: {lookback}
  predict_window: {predict}
  max_context: 512
  clip: 5.0
  train_ratio: {train_ratio:.6f}
  val_ratio: {val_ratio:.6f}
  test_ratio: 0.0

training:
  tokenizer_epochs: {tok_epochs}
  basemodel_epochs: {model_epochs}
  batch_size: {batch_size}
  log_interval: 50
  num_workers: 4
  seed: 42
  tokenizer_learning_rate: 0.0002
  predictor_learning_rate: 0.000001
  adam_beta1: 0.9
  adam_beta2: 0.95
  adam_weight_decay: 0.1
  accumulation_steps: 1

model_paths:
  pretrained_tokenizer: "{pretrained_tokenizer}"
  pretrained_predictor: "{pretrained_predictor}"
  exp_name: "{exp_name}"
  base_path: "{base_path}"
  base_save_path: ""
  finetuned_tokenizer: ""
  tokenizer_save_name: "tokenizer"
  basemodel_save_name: "basemodel"

experiment:
  name: "{exp_name}"
  description: "Kronos fine-tuned on forex {tf} candles, {data_range}"
  use_comet: false
  train_tokenizer: true
  train_basemodel: true
  skip_existing: false

device:
  use_cuda: true
  device_id: 0
"""


def _fmt(ts: int) -> str:
    return datetime.fromtimestamp(ts, timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


def write_csv(path: Path, candles: list):
    with path.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["timestamps", "open", "high", "low", "close", "volume", "amount"])
        for c in candles:
            w.writerow([_fmt(c.open_time), c.open, c.high, c.low, c.close, c.tick_volume, 0])


def main(argv=None):
    ap = argparse.ArgumentParser(prog="forexapp.models.finetune.prepare_data", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pairs")
    ap.add_argument("--tf", default="5m")
    ap.add_argument("--train-end", required=True)
    ap.add_argument("--val-end", required=True)
    ap.add_argument("--start", help="first candle to use (default: all stored)")
    ap.add_argument("--out", default=str(APP_DIR / "models" / "finetune" / "data"))
    ap.add_argument("--chain", action="store_true",
                    help="each pair continues from the previous pair's fine-tuned checkpoints (one model for all pairs)")
    ap.add_argument("--lookback", type=int, default=400)
    ap.add_argument("--predict", type=int, default=24)
    ap.add_argument("--base", default="NeoQuasar/Kronos-small", help="or NeoQuasar/Kronos-base with a bigger GPU")
    ap.add_argument("--tokenizer", default="NeoQuasar/Kronos-Tokenizer-base")
    ap.add_argument("--batch-size", type=int, default=32)
    ap.add_argument("--tokenizer-epochs", type=int, default=10)
    ap.add_argument("--model-epochs", type=int, default=10)
    a = ap.parse_args(argv)
    cfg = Config.from_env()
    store = Store(cfg.db_url)
    tf = norm_tf(a.tf)
    pairs = [p.strip().upper() for p in a.pairs.split(",")] if a.pairs else cfg.pairs
    train_end, val_end = parse_iso(a.train_end + "T23:59:59Z"), parse_iso(a.val_end + "T23:59:59Z")
    if val_end <= train_end:
        raise SystemExit("--val-end must be after --train-end")
    start = parse_iso(a.start) if a.start else None
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    ckpt = APP_DIR / "models" / "checkpoints"
    ckpt.mkdir(parents=True, exist_ok=True)
    prev_exp = None
    for p in pairs:
        rows = store.get_candles(p, tf, limit=None, start=start)
        if not rows:
            print("%s: no %s candles stored, skipped" % (p, tf))
            continue
        tv = [c for c in rows if c.open_time <= val_end]
        test = [c for c in rows if c.open_time > val_end]
        n_train = sum(c.open_time <= train_end for c in tv)
        if not tv or n_train == 0 or n_train == len(tv):
            print("%s: the dates leave no training or no validation candles, skipped" % p)
            continue
        write_csv(out / ("%s_%s_trainval.csv" % (p, tf)), tv)
        write_csv(out / ("%s_%s_test.csv" % (p, tf)), test)
        rng = "%s..%s" % (_fmt(rows[0].open_time)[:10], _fmt(tv[-1].open_time)[:10])
        exp = "forex-%s-%s-%s-%s" % (a.base.split("/")[-1].lower(), p, tf, datetime.now(timezone.utc).strftime("%Y%m%d"))
        tok, pred = a.tokenizer, a.base
        if a.chain and prev_exp:
            tok = str((ckpt / prev_exp / "tokenizer" / "best_model").resolve())
            pred = str((ckpt / prev_exp / "basemodel" / "best_model").resolve())
        cpath = out / ("%s_%s_config.yaml" % (p, tf))
        cpath.write_text(CONFIG_TEMPLATE.format(
            config_path=cpath, data_path=(out / ("%s_%s_trainval.csv" % (p, tf))).resolve(), lookback=a.lookback,
            predict=a.predict, train_ratio=n_train / len(tv), val_ratio=1 - n_train / len(tv),
            tok_epochs=a.tokenizer_epochs, model_epochs=a.model_epochs, batch_size=a.batch_size,
            pretrained_tokenizer=tok, pretrained_predictor=pred, exp_name=exp,
            base_path=str(ckpt.resolve()) + "/", tf=tf, data_range=rng))
        prev_exp = exp
        print("%s: train %d, validation %d, test %d candles (untouched) -> %s" % (p, n_train, len(tv) - n_train,
                                                                                  len(test), cpath))
    print("Next, from the Kronos repo, for each config:  python finetune_csv/train_sequential.py --config <config>")


if __name__ == "__main__":
    main()
